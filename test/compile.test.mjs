import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { parseRule } from '../src/rules.mjs';
import { compileRule, compileAll, readCompiledHash, testFileName, ruleIdFromTestPath } from '../src/compile.mjs';
import { loadRulePack } from '../src/rules.mjs';
import { tmp } from './helpers.mjs';

const { rule } = parseRule(readFileSync(new URL('../rules/house/PL-THEME.md', import.meta.url), 'utf8'), '@house/PL-THEME.md');

test('compiles a rule into Kane test markdown: one H2 per step, tags and a hash', () => {
  const md = compileRule(rule);
  assert.match(md, /^---\nmode: testing\ntags: \[plumb, pl-theme, blocking\]\nmax_steps: 25\n---/);
  assert.equal((md.match(/^## /gm) ?? []).length, 3);
  assert.match(md, /<!-- generated by plumb from @house\/PL-THEME.md \(rule [0-9a-f]{12}\)/);
  assert.match(md, /Verify the page background colour changed\./);
  assert.doesNotMatch(md, /\{\{/);
});

test('step headings are short labels, the body is the full instruction', () => {
  const md = compileRule(rule);
  const headings = md.split('\n').filter((l) => l.startsWith('## '));
  assert.ok(headings.every((h) => h.length < 70));
});

test('file name and rule id round trip', () => {
  assert.equal(testFileName('PL-THEME'), 'pl-theme_test.md');
  assert.equal(ruleIdFromTestPath('/x/tests/plumb/pl-theme_test.md'), 'PL-THEME');
});

test('compileAll writes only stale tests and reports orphans', () => {
  const root = tmp();
  const pack = loadRulePack({ root, dirs: ['@house'], only: ['PL-THEME', 'PL-NAV'] });
  const first = compileAll(pack.rules, { root, testsDir: 'tests/plumb', url: null, maxSteps: 25 });
  assert.equal(first.written.length, 2);
  const again = compileAll(pack.rules, { root, testsDir: 'tests/plumb', url: null, maxSteps: 25 });
  assert.equal(again.written.length, 0);
  assert.equal(again.current.length, 2);
  const file = join(root, 'tests/plumb/pl-theme_test.md');
  assert.equal(readCompiledHash(file), rule.sha);
  writeFileSync(file, readFileSync(file, 'utf8').replace(rule.sha, '000000000000'));
  const stale = compileAll(pack.rules, { root, testsDir: 'tests/plumb', url: null, maxSteps: 25 });
  assert.deepEqual(stale.written.map((p) => p.split('/').pop()), ['pl-theme_test.md']);
  const fewer = compileAll(pack.rules.slice(0, 1), { root, testsDir: 'tests/plumb', url: null, maxSteps: 25 });
  assert.equal(fewer.orphans.length, 1);
});
