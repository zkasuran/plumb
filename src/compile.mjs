import { mkdirSync, readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { join, basename } from 'node:path';
import { truncate } from './util.mjs';

/** Kane names the output folder after the file stem, so keep stems short and stable. */
export function testStem(ruleId) {
  return ruleId.toLowerCase();
}

export function testFileName(ruleId) {
  return `${testStem(ruleId)}_test.md`;
}

function headingFor(step, index) {
  const first = step.split(/(?<=[.!?])\s/)[0].replace(/[`*_#]/g, '').trim();
  return `${index + 1}. ${truncate(first, 56).replace(/…$/, '')}`;
}

/**
 * Compile one rule into the markdown Kane runs. The header comment carries the rule hash,
 * so `plumb compile --check` can tell a stale test from a current one.
 */
export function compileRule(rule, { url = null, maxSteps = 25 } = {}) {
  const fm = [
    '---',
    'mode: testing',
    `tags: [plumb, ${rule.id.toLowerCase()}, ${rule.severity}]`,
    `max_steps: ${rule.maxSteps ?? maxSteps}`,
    ...(url ? [`url: ${url}`] : []),
    '---',
    '',
    `# ${rule.id} ${rule.title}`,
    '',
    `<!-- generated by plumb from ${rule.file} (rule ${rule.sha}). Edit the rule, not this file. -->`,
    '',
  ];
  const body = rule.steps.flatMap((step, i) => [`## ${headingFor(step, i)}`, step, '']);
  return [...fm, ...body].join('\n').replace(/\n{3,}/g, '\n\n').trimEnd() + '\n';
}

const HASH_RE = /<!-- generated by plumb from (.+?) \(rule ([0-9a-f]{12})\)/;

export function readCompiledHash(path) {
  if (!existsSync(path)) return null;
  const m = readFileSync(path, 'utf8').match(HASH_RE);
  return m ? m[2] : null;
}

/**
 * Write tests for every rule whose compiled file is missing or stale. Returns what changed.
 * A rule that was edited keeps its folder of recordings; Kane re-authors the changed steps
 * on its own when the step text no longer matches.
 */
export function compileAll(rules, { root, testsDir, url, maxSteps }) {
  const dir = join(root, testsDir);
  mkdirSync(dir, { recursive: true });
  const written = [];
  const current = [];
  for (const rule of rules) {
    const path = join(dir, testFileName(rule.id));
    if (readCompiledHash(path) === rule.sha) {
      current.push(path);
      continue;
    }
    writeFileSync(path, compileRule(rule, { url, maxSteps }));
    written.push(path);
  }
  const wanted = new Set(rules.map((r) => testFileName(r.id)));
  const orphans = existsSync(dir)
    ? readdirSync(dir).filter((f) => f.endsWith('_test.md') && !wanted.has(f)).map((f) => join(dir, f))
    : [];
  return { dir, written, current, orphans };
}

export function ruleIdFromTestPath(path) {
  const name = basename(path).replace(/_test\.md$/, '');
  return name.toUpperCase();
}
